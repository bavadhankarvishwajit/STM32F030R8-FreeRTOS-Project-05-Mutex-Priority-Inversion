#include "gpio.h"

/******************************************************************************
 * Function: GPIO_Init
 * Purpose : Configure PA5 as Output (User LED)
 ******************************************************************************/
void GPIO_Init(void)
{
    /*-----------------------------------------------------------
     * Step 1 : Enable GPIOA Clock
     *----------------------------------------------------------*/
    LED_GPIO_CLK_EN();

    /*-----------------------------------------------------------
     * Step 2 : Configure PA5 as General Purpose Output
     * MODER[11:10] = 01
     *----------------------------------------------------------*/
    LED_GPIO_PORT->MODER &= ~(3U << (LED_PIN * 2));
    LED_GPIO_PORT->MODER |=  (1U << (LED_PIN * 2));

    /*-----------------------------------------------------------
     * Step 3 : Output Type = Push Pull
     * OTYPER[5] = 0
     *----------------------------------------------------------*/
    LED_GPIO_PORT->OTYPER &= ~(1U << LED_PIN);

    /*-----------------------------------------------------------
     * Step 4 : Output Speed = High Speed
     * OSPEEDR[11:10] = 11
     *----------------------------------------------------------*/
    LED_GPIO_PORT->OSPEEDR &= ~(3U << (LED_PIN * 2));
    LED_GPIO_PORT->OSPEEDR |=  (3U << (LED_PIN * 2));

    /*-----------------------------------------------------------
     * Step 5 : No Pull-Up / Pull-Down
     * PUPDR[11:10] = 00
     *----------------------------------------------------------*/
    LED_GPIO_PORT->PUPDR &= ~(3U << (LED_PIN * 2));

    /*-----------------------------------------------------------
     * Step 6 : LED OFF Initially
     *----------------------------------------------------------*/
    LED_OFF();
}

/******************************************************************************
 * Function: LED_ON
 ******************************************************************************/
void LED_ON(void)
{
    LED_GPIO_PORT->BSRR = (1U << LED_PIN);
}

/******************************************************************************
 * Function: LED_OFF
 ******************************************************************************/
void LED_OFF(void)
{
    LED_GPIO_PORT->BRR = (1U << LED_PIN);
}

/******************************************************************************
 * Function: LED_TOGGLE
 ******************************************************************************/
void LED_TOGGLE(void)
{
    LED_GPIO_PORT->ODR ^= (1U << LED_PIN);
}
